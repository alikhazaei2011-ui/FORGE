  function getById(id) {
    return exercises.find(exercise => exercise.id === id) || null;
  }

  function search(query = "") {
    const term = String(query).trim().toLowerCase();

    if (!term) return getAll();

    return exercises.filter(exercise => {
      const searchable = [
        exercise.name,
        exercise.category,
        ...exercise.muscles,
        exercise.equipment,
        exercise.level
      ].join(" ").toLowerCase();

      return searchable.includes(term);
    });
  }

